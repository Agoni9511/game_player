insert into pw_sku_level_price(sku_id,player_level_id,price,market_price,enabled)
select k.id,l.id,
  case l.level_code when 'STARTER' then k.price*0.80 when 'MASTER' then k.price*1.50 else k.price end,
  k.market_price,true
from pw_product_sku k
join pw_product p on p.id=k.product_id and p.product_type='SERVICE'
cross join pw_player_level l
where not exists(select 1 from pw_sku_level_price x where x.sku_id=k.id and x.player_level_id=l.id);
