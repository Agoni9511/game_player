-- Replace the V20 one-row-per-order earning constraint with a member-scoped link.
create table pw_player_earning_v42 (
  id bigint generated by default as identity primary key,
  earning_no varchar(48) not null unique,
  order_id bigint not null,
  order_member_id bigint,
  settlement_detail_id bigint,
  player_id bigint not null,
  order_amount decimal(14,2) not null,
  commission_rate decimal(6,4) not null,
  commission_amount decimal(14,2) not null,
  player_amount decimal(14,2) not null,
  earning_status varchar(20) not null,
  settled_at timestamp,
  created_at timestamp not null default current_timestamp,
  updated_at timestamp not null default current_timestamp
);

insert into pw_player_earning_v42(
  id,earning_no,order_id,order_member_id,player_id,order_amount,commission_rate,
  commission_amount,player_amount,earning_status,settled_at,created_at,updated_at
)
select e.id,e.earning_no,e.order_id,
  (select min(m.id) from pw_order_member m where m.order_id=e.order_id and m.player_id=e.player_id),
  e.player_id,e.order_amount,e.commission_rate,e.commission_amount,e.player_amount,
  e.earning_status,e.settled_at,e.created_at,e.updated_at
from pw_player_earning e;

